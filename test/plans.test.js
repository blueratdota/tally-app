const assert = require('node:assert/strict');
const { occurrence, dueCharges, nextChargeDate, transactionKey } = require('../netlify/functions/lib/plans');
assert.equal(occurrence('2026-01-31', 'monthly', 1), '2026-02-28');
assert.equal(occurrence('2026-01-31', 'monthly', 2), '2026-03-31');
assert.equal(occurrence('2024-02-29', 'yearly', 1), '2025-02-28');
assert.equal(occurrence('2026-11-30', 'daily', 1), '2026-12-01');
assert.equal(occurrence('2026-12-28', 'weekly', 1), '2027-01-04');
assert.equal(occurrence('2026-01-20', 'fortnightly', 2), '2026-02-17');
assert.equal(occurrence('2026-11-30', 'quarterly', 1), '2027-02-28');
const plan = { id: 'p', kind: 'recurring', active: true, frequency: 'monthly', start_date: '2026-01-31', amount: 99.95, account_id: 's', person: 'p1', category: 'Subscription', description: 'Subscription' };
const rows = dueCharges(plan, '2026-03-31', new Set());
assert.deepEqual(rows.map(t => t.date), ['2026-01-31', '2026-02-28', '2026-03-31']);
assert.equal(dueCharges(plan, '2026-03-31', new Set(rows.map(t => t.id))).length, 0);
assert.equal(dueCharges({ ...plan, active: false }, '2026-03-31', new Set()).length, 0);
assert.equal(dueCharges({ ...plan, end_date: '2026-02-28' }, '2026-03-31', new Set()).length, 2);
assert.equal(nextChargeDate(plan, '2026-02-28'), '2026-03-31');
assert.equal(nextChargeDate({ ...plan, end_date: '2026-02-28' }, '2026-02-28'), '');
assert.equal(transactionKey({ date: '2026-01-01', type: 'expense', amount: '100.00', description: ' Shop ', from_account_id: 's' }), transactionKey({ date: '2026-01-01', type: 'expense', amount: 100, description: 'shop', from_account_id: 's', category: 'Other', person: 'p2' }));
console.log('All recurrence and duplicate matching checks passed.');
